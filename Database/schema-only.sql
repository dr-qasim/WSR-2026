CREATE OR REPLACE FUNCTION validate_recipe_total_before_approval()
RETURNS trigger
AS $$
DECLARE
    component_total numeric(10,2);
    IF NEW.status = 3 THEN
        SELECT COALESCE(SUM(percentage), 0)
        INTO component_total
        FROM recipe_components
        WHERE recipe_version_id = NEW.id;

        IF ROUND(component_total, 2) <> 100.00 THEN
            RAISE EXCEPTION
                'Cannot approve recipe version %, component total must equal 100%%. Actual total: %',
                NEW.id,
                component_total;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION validate_recipe_total_after_component_change()
RETURNS trigger
AS $$
DECLARE
    affected_recipe_version_id integer;
    current_status integer;
    component_total numeric(10,2);
    affected_recipe_version_id := COALESCE(NEW.recipe_version_id, OLD.recipe_version_id);

    SELECT status
    INTO current_status
    FROM recipe_versions
    WHERE id = affected_recipe_version_id;

    IF current_status = 3 THEN
        SELECT COALESCE(SUM(percentage), 0)
        INTO component_total
        FROM recipe_components
        WHERE recipe_version_id = affected_recipe_version_id;

        IF ROUND(component_total, 2) <> 100.00 THEN
            RAISE EXCEPTION
                'Approved recipe version % must keep component total equal to 100%%. Actual total: %',
                affected_recipe_version_id,
                component_total;

    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION validate_production_batch_configuration()
RETURNS trigger
AS $$
DECLARE
    recipe_status integer;
    recipe_is_active boolean;
    technology_status integer;
    technology_is_active boolean;
    extruder_is_active boolean;
    extruder_technology_card_id integer;
    SELECT status, is_active
    INTO recipe_status, recipe_is_active
    FROM recipe_versions
    WHERE id = NEW.recipe_version_id
      AND product_id = NEW.product_id;

    IF NOT FOUND OR recipe_status <> 3 OR NOT recipe_is_active THEN
        RAISE EXCEPTION
            'Production batch % must use an active approved recipe version for product %',
            NEW.batch_number,
            NEW.product_id;

    SELECT status, is_active
    INTO technology_status, technology_is_active
    FROM technology_cards
    WHERE id = NEW.technology_card_id
      AND product_id = NEW.product_id;

    IF NOT FOUND OR technology_status <> 3 OR NOT technology_is_active THEN
        RAISE EXCEPTION
            'Production batch % must use an active approved technology card for product %',
            NEW.batch_number,
            NEW.product_id;

    IF NEW.extruder_program_id IS NOT NULL THEN
        SELECT is_active, technology_card_id
        INTO extruder_is_active, extruder_technology_card_id
        FROM extruder_programs
        WHERE id = NEW.extruder_program_id
          AND product_id = NEW.product_id;

        IF NOT FOUND OR NOT extruder_is_active THEN
            RAISE EXCEPTION
                'Production batch % must use an active extruder program for product %',
                NEW.batch_number,
                NEW.product_id;

        IF extruder_technology_card_id IS NOT NULL
           AND extruder_technology_card_id <> NEW.technology_card_id THEN
            RAISE EXCEPTION
                'Extruder program % is not linked to technology card %',
                NEW.extruder_program_id,
                NEW.technology_card_id;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

