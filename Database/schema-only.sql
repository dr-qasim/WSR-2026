CREATE OR REPLACE FUNCTION validate_laboratory_test_specification_matches_subject()
RETURNS trigger
AS $$
DECLARE
    lot_raw_material_id integer;
    batch_product_id integer;
    specification_subject_type integer;
    specification_raw_material_id integer;
    specification_product_id integer;
    SELECT subject_type, raw_material_id, product_id
    INTO specification_subject_type, specification_raw_material_id, specification_product_id
    FROM quality_specifications
    WHERE id = NEW.quality_specification_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Quality specification % does not exist',
            NEW.quality_specification_id;

    IF NEW.subject_type = 1 THEN
        SELECT raw_material_id
        INTO lot_raw_material_id
        FROM raw_material_lots
        WHERE id = NEW.raw_material_lot_id;

        IF specification_subject_type <> 1
           OR specification_raw_material_id IS DISTINCT FROM lot_raw_material_id THEN
            RAISE EXCEPTION
                'Laboratory test % uses a specification that does not match raw material lot %',
                NEW.test_number,
                NEW.raw_material_lot_id;
    ELSIF NEW.subject_type = 2 THEN
        SELECT product_id
        INTO batch_product_id
        FROM production_batches
        WHERE id = NEW.production_batch_id;

        IF specification_subject_type <> 2
           OR specification_product_id IS DISTINCT FROM batch_product_id THEN
            RAISE EXCEPTION
                'Laboratory test % uses a specification that does not match production batch %',
                NEW.test_number,
                NEW.production_batch_id;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

